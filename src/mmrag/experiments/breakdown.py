"""Scores by query type and by number of relevant pages: breakdown.json -> breakdown.md.

    uv run python -m mmrag.experiments.breakdown

``results/breakdown.json`` names, per subset, the runs to put side by side:

    {"hr": {"baseline": "2026-11-14_hr_baseline", "one-shot": "...", "final": "..."}}

Everything is read from the stored per-query results (``per_query.jsonl``, and
``answers.jsonl`` where the run was judged); nothing is run. A query with several
types counts in each of them.
"""

from __future__ import annotations

from pathlib import Path

from mmrag.eval.breakdown import RELEVANT_BINS, relevant_bin
from mmrag.experiments import common
from mmrag.experiments.ladder import per_query


def groups(results: Path) -> dict[str, list[str]]:
    """Group name -> query ids, query types first (largest first), then the page bins."""
    types: dict[str, list[str]] = {}
    bins: dict[str, list[str]] = {f"{name} relevant": [] for name, _, _ in RELEVANT_BINS}
    for row in common.read_jsonl(results / "per_query.jsonl"):
        qid = str(row["query_id"])
        for kind in row["query_types"] or ["(none)"]:
            types.setdefault(kind, []).append(qid)
        bins[f"{relevant_bin(row['n_relevant'])} relevant"].append(qid)
    ordered = dict(sorted(types.items(), key=lambda item: -len(item[1])))
    return {"all": [q for qids in bins.values() for q in qids], **ordered, **bins}


def _mean(scores: dict[str, float], qids: list[str]) -> str:
    values = [scores[q] for q in qids if q in scores]  # ungraded answers are left out
    return f"{sum(values) / len(values):.3f}" if values else "-"


def breakdown_table(root: Path) -> str:
    spec = common.read_json(root / "breakdown.json")
    systems = list(next(iter(spec.values())))
    header = ["subset", "group", "queries"]
    header += [f"NDCG@10 {s}" for s in systems] + [f"answer {s}" for s in systems]
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    for subset, runs in spec.items():
        scores = {
            (metric, system): per_query(root / run, metric)
            if metric == "ndcg" or (root / run / "answers.jsonl").exists()
            else {}
            for metric in ("ndcg", "answer")
            for system, run in runs.items()
        }
        for group, qids in groups(root / runs[systems[0]]).items():
            cells = [subset, group, str(len(qids))]
            cells += [_mean(scores[m, s], qids) for m in ("ndcg", "answer") for s in systems]
            lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


HEADER = """# Scores by query type and by number of relevant pages

Mean NDCG@10 and mean answer score (LLM judge; "-" where the run was not judged)
of the baseline, the best one-shot system and the final system. A query with
several types counts in each. Generated by `python -m mmrag.experiments.breakdown`
from `breakdown.json` and the stored per-query results.

"""


def main() -> None:
    root = common.ROOT / "results"
    table = breakdown_table(root)
    (root / "breakdown.md").write_text(HEADER + table, encoding="utf-8")
    print(table)


if __name__ == "__main__":
    main()
