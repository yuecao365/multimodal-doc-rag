"""The improvement ladder: results/ladder.json -> results/ladder.md.

    uv run python -m mmrag.experiments.ladder            # the ladder on the dev set
    uv run python -m mmrag.experiments.ladder heldout    # results/heldout.json -> heldout.md

``results/ladder.json`` lists the steps in order. Each row names a results
directory and, for a candidate change, the run it is compared with:

    {"step": "1", "change": "+ BM25, fused with RRF", "run": "2026-11-14_hr_text_bm25",
     "against": "2026-11-14_hr_baseline", "kind": "quality", "metric": "ndcg"}

kind      "baseline" / "reference" (no test), "quality" (kept if it is better,
          p < 0.05), "efficiency" (kept unless it is worse, p < 0.05) or "ablation"
          (tested, no decision: the held-out set is not used to choose anything).
metric    "ndcg" (NDCG@10 per query) or "answer" (judge score per query).

Every number in the table is read from the results directories; the decision
"kept" is computed here, never typed in.
"""

from __future__ import annotations

import sys
from pathlib import Path

from mmrag.eval.significance import paired_test
from mmrag.experiments import common

COLUMNS = [
    "step", "change", "NDCG@10", "Recall@10", "answer score", "index KB/page",
    "search $/query", "difference [95% CI]", "p", "kept", "run",
]  # fmt: skip


def per_query(results: Path, metric: str) -> dict[str, float]:
    """One score per query from a results directory."""
    if metric == "ndcg":
        rows = common.read_jsonl(results / "per_query.jsonl")
        return {str(r["query_id"]): r["ndcg_cut_10"] for r in rows}
    rows = common.read_jsonl(results / "answers.jsonl")
    return {str(r["query_id"]): r["judge_score"] for r in rows if r["judge_score"] is not None}


def compare(new: Path, old: Path, metric: str) -> dict:
    a, b = per_query(new, metric), per_query(old, metric)
    both = sorted(set(a) & set(b))  # an answer the judge could not grade drops the pair
    return paired_test({q: a[q] for q in both}, {q: b[q] for q in both})


def decide(kind: str, test: dict) -> bool:
    worse = test["mean"] < 0 and test["p_value"] < 0.05
    better = test["mean"] > 0 and test["p_value"] < 0.05
    return better if kind == "quality" else not worse


def _load(path: Path):
    return common.read_json(path) if path.exists() else {}


def _fmt(value, digits: int = 3) -> str:
    return "-" if value is None else f"{value:.{digits}f}"


def row(spec: dict, root: Path) -> dict[str, str]:
    results = root / spec["run"]
    metrics = _load(results / "metrics.json")
    cost = _load(results / "cost.json")
    answers = _load(results / "answer_metrics.json").get("answer") or {}
    per_page = cost.get("index_storage_bytes_per_page")
    out = {
        "step": spec["step"],
        "change": spec["change"],
        "NDCG@10": _fmt(metrics.get("ndcg_cut_10")),
        "Recall@10": _fmt(metrics.get("recall_10")),
        "answer score": _fmt(answers.get("mean_score")),
        "index KB/page": _fmt(per_page / 1024 if per_page is not None else None, 1),
        "search $/query": _fmt(cost.get("search_cost_usd_per_query"), 5),
        "difference [95% CI]": "-",
        "p": "-",
        "kept": "-",
        "run": f"[{spec['run']}]({spec['run']}/)",
    }
    if spec.get("against"):
        test = compare(results, root / spec["against"], spec["metric"])
        low, high = test["ci95"]
        out["difference [95% CI]"] = (
            f"{test['mean']:+.3f} [{low:+.3f}, {high:+.3f}] {spec['metric']}"
        )
        out["p"] = f"{test['p_value']:.4f}"
        if spec["kind"] != "ablation":
            out["kept"] = "yes" if decide(spec["kind"], test) else "no"
    return out


def ladder_table(root: Path, name: str = "ladder") -> str:
    rows = [row(spec, root) for spec in common.read_json(root / f"{name}.json")]
    lines = ["| " + " | ".join(COLUMNS) + " |", "|" + "---|" * len(COLUMNS)]
    lines += ["| " + " | ".join(r[c] for c in COLUMNS) + " |" for r in rows]
    return "\n".join(lines) + "\n"


HEADERS = {
    "ladder": """# Improvement ladder (development set: vidore_v3_hr, 318 English queries)

Each candidate step is compared with the system it was added to ("difference"),
with a paired randomization test over queries. A quality change is kept only if it
is better with p < 0.05; an efficiency change is kept unless it is worse with
p < 0.05. Rows marked "ref" are reference runs, not steps. Generated by
`python -m mmrag.experiments.ladder` from `ladder.json`.

""",
    "heldout": """# Held-out test (vidore_v3_finance_en, 309 English queries)

Every setting was frozen on the development set. "final" is compared with the
baseline; each "without ..." row removes one kept change from the final system and
is compared with the final system (paired randomization test over queries).
Nothing is decided here. Generated by `python -m mmrag.experiments.ladder heldout`
from `heldout.json`.

""",
}


def main(argv: list[str] | None = None) -> None:
    name = (sys.argv[1:] if argv is None else argv) or ["ladder"]
    root = common.ROOT / "results"
    table = ladder_table(root, name[0])
    (root / f"{name[0]}.md").write_text(HEADERS[name[0]] + table, encoding="utf-8")
    print(table)


if __name__ == "__main__":
    main()
